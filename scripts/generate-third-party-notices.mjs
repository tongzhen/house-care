import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const root = process.cwd();
const check = process.argv.includes('--check');
const lock = JSON.parse(readFileSync(join(root, 'package-lock.json'), 'utf8'));
const licenceOverrides = new Map([['exit@0.1.2', 'MIT']]);

function packagePathFromLockKey(key) {
  return key.startsWith('node_modules/') ? join(root, key) : null;
}

function licenseFile(packagePath) {
  const name = readdirSync(packagePath).find((entry) => /^(licen[cs]e|copying|notice)([-_.].*)?$/i.test(entry));
  return name ? readFileSync(join(packagePath, name), 'utf8').trim() : null;
}

const licenseTextByIdentifier = new Map();
for (const [key, value] of Object.entries(lock.packages)) {
  if (!key.startsWith('node_modules/') || value.optional || !existsSync(join(root, key, 'package.json'))) continue;
  const packagePath = join(root, key);
  const manifest = JSON.parse(readFileSync(join(packagePath, 'package.json'), 'utf8'));
  if (typeof manifest.license !== 'string') continue;
  const text = licenseFile(packagePath);
  if (text && !licenseTextByIdentifier.has(manifest.license)) licenseTextByIdentifier.set(manifest.license, text);
}

function textForLicense(license) {
  const direct = licenseTextByIdentifier.get(license);
  if (direct) return direct;
  const alternatives = license.replaceAll(/[()]/g, '').split(' OR ').map((identifier) => licenseTextByIdentifier.get(identifier));
  return alternatives.every(Boolean) ? alternatives.join('\n\n---\n\n') : null;
}

const notices = Object.entries(lock.packages)
  .filter(([key, value]) => key && key.startsWith('node_modules/') && !value.link && !value.dev && !value.optional && existsSync(join(root, key, 'package.json')))
  .map(([key, value]) => {
    const packagePath = packagePathFromLockKey(key);
    if (!packagePath) throw new Error(`Invalid package path: ${key}`);
    const manifest = JSON.parse(readFileSync(join(packagePath, 'package.json'), 'utf8'));
    const license = typeof manifest.license === 'string' ? manifest.license : typeof value.license === 'string' ? value.license : licenceOverrides.get(`${manifest.name}@${manifest.version}`) ?? 'UNKNOWN';
    const text = licenseFile(packagePath) ?? textForLicense(license);
    return { name: manifest.name, version: manifest.version, copyright: manifest.author?.name ?? null, license, licenseText: text ?? `Licence text was not found for ${license}.` };
  })
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const missing = notices.filter((notice) => notice.license === 'UNKNOWN' || notice.licenseText.startsWith('Licence text was not found'));
if (missing.length) throw new Error(`Missing licence data: ${missing.map((notice) => `${notice.name}@${notice.version}`).join(', ')}`);

const output = `// Generated by scripts/generate-third-party-notices.mjs. Do not edit manually.\n\nexport interface ThirdPartyNotice {\n  name: string;\n  version: string;\n  copyright: string | null;\n  license: string;\n  licenseText: string;\n}\n\nexport const thirdPartyNotices: ThirdPartyNotice[] = ${JSON.stringify(notices, null, 2)};\n`;
const target = join(root, 'src/generated/thirdPartyNotices.ts');

if (check) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== output) throw new Error('Third-party notices are out of date. Run npm run generate:notices.');
} else {
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, output);
}
